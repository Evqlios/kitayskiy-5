def strip_list_in_parens(q, opts):
    """Убирает хвост «(a / b)», если он просто повторяет варианты ответа."""
    m = re.search(r'\s*[（(]([^()（）]*)[)）]\s*$', q)
    if not m: return q
    toks = {t.strip() for t in re.split(r'\s*/\s*', m.group(1)) if t.strip()}
    if toks and toks == {o.strip() for o in opts}:
        return q[:m.start()].rstrip()
    return q


def fix_sgu_q(e):
    q, t = e['q'], e['t']
    if e['id'] in SGU_Q:
        new, old_start = SGU_Q[e['id']]
        assert q == old_start, (e['id'], q)
        return new
    if t == 'mc':
        # --- инструкции с отсылкой к рамке/столбцу ---
        rules = [
            (r'^Вставь слово из правого столбца \([^)]*\):', 'Вставь пропущенное слово:'),
            (r'^Вставь счётное слово из рамки \([^)]*\):', 'Вставь счётное слово:'),
            (r'^Вставь слово из рамки( \([^)]*\))?:', 'Вставь пропущенное слово:'),
            (r'^Заполни пропуск словом из рамки \([^)]*\):', 'Вставь пропущенное слово:'),
            (r'^Выбери счётное слово \([^)]*\):', 'Выбери счётное слово:'),
            (r'^Выбери слово \([^)]*\):', 'Вставь пропущенное слово:'),
            (r'^Вставь слово \([^)]*\):', 'Вставь пропущенное слово:'),
            (r'^Исправь ошибку по правилу учебника:', 'Исправь ошибку:'),
            (r'^Соедини фразу с переводом:', 'Выбери перевод:'),
        ]
        for pat, rep in rules:
            q2 = re.sub(pat, rep, q, count=1)
            if q2 != q:
                q = q2
                break
        if re.match(r'^Выбери слово:', q):
            q = re.sub(r'^Выбери слово:', 'Вставь пропущенное слово:', q)
        q = strip_list_in_parens(q, e['opts'])
        # --- задания без инструкции ---
        if not re.match(r'\s*[А-Яа-я]', q):
            if '_' in q or '☐' in q:
                q = 'Заполни пропуск:  ' + q
            elif e.get('ctx'):
                q = 'Вопрос по тексту:  ' + q
            else:
                raise AssertionError(('нет инструкции', e['id'], q))
        return q
    # build
    q = re.sub(r'^Составь фразу из слов рамки:\s*', '', q)
    q = re.sub(r'Задай вопрос к выделенным словам \(([^)]*)\)', r'Задай вопрос к словам «\1»', q)
    q = re.sub(r'Задай вопрос к выделенному слову \(([^)]*)\)', r'Задай вопрос к слову «\1»', q)
    return q


def fix_exp(e):
    i = e['id']
    if i in SGU_EXP:
        if SGU_EXP[i] is None:
            new = re.sub(r'\s*Слово \S+ в рамке лишнее\.$', '', e['exp'])
            assert new != e['exp'], i
            return new
        new, old = SGU_EXP[i]
        assert e['exp'].count(old) == 1, i
        return e['exp'].replace(old, new)
    return e['exp']


report = {'q': 0, 'exp': 0}
changes = []
for key in ('sgu', 'gram'):
    for m in list(re.finditer(r'"%s":\[' % key, s))[::-1]:       # с конца, чтобы смещения не плыли
        st = m.end() - 1
        arr, end = dec.raw_decode(s, st)
        assert json.dumps(arr, ensure_ascii=False, separators=(',', ':')) == s[st:end], 'круговая проверка JSON'
        for e in arr:
            if key == 'gram':
                if e['id'] in GRAM_Q:
                    new, old_start = GRAM_Q[e['id']]
                    assert e['q'].startswith(old_start), (e['id'], e['q'])
                    new_q = new
                else:
                    new_q = e['q']
            else:
                new_q = fix_sgu_q(e)
                new_exp = fix_exp(e)
                if new_exp != e['exp']:
                    changes.append((e['id'], 'exp', e['exp'], new_exp)); e['exp'] = new_exp; report['exp'] += 1
            if new_q != e['q']:
                changes.append((e['id'], 'q', e['q'], new_q)); e['q'] = new_q; report['q'] += 1
        s = s[:st] + json.dumps(arr, ensure_ascii=False, separators=(',', ':')) + s[end:]

