import json, sys

SITE = '/home/user/kitayskiy-5/site69.html'
s = open(SITE, encoding='utf-8').read()

# ---------- 1. загрузка двух массивов статей: литерал THEORY13 (21 шт.) и D13.theory (19 шт.) ----------
LIT_START = s.index('const THEORY13 = [') + len('const THEORY13 = ')
LIT_END = s.index('];', LIT_START) + 1
lit = json.loads(s[LIT_START:LIT_END].replace('<\\/', '</'))

D_START = s.index('const D13 = ') + len('const D13 = ')
D_END = s.index(";\n['words', 'chars', 'sents', 'sgu', 'gram', 'phon'].forEach", D_START)
D13 = json.loads(s[D_START:D_END].replace('<\\/', '</'))
d13t = D13['theory']


def art(aid):
    """Найти статью по id в обоих массивах."""
    for arr in (lit, d13t):
        for a in arr:
            if a['id'] == aid:
                return a
    raise KeyError(aid)


def add_r(aid, text, after=None):
    """Добавить абзац правила в конец списка r (или после абзаца с индексом after)."""
    a = art(aid)
    assert text not in a['r'], (aid, 'дубль абзаца')
    if after is None:
        a['r'].append(text)
    else:
        a['r'].insert(after + 1, text)


def add_ex(aid, hz, py, ru):
    a = art(aid)
    assert all(e[0] != hz for e in a['ex']), (aid, hz, 'дубль примера')
    a['ex'].append([hz, py, ru])


def add_src(aid, extra):
    a = art(aid)
    assert extra not in a['src'], (aid, 'дубль источника')
    a['src'] += '; ' + extra


