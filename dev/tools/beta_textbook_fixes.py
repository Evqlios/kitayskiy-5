#!/usr/bin/env python3
"""Beta: мелкие правки по сверке с учебником (сканы учебника, 4 PDF: с. 1–29, 30–69, 69–109, 109–145; отчёты dev/data_sgu/tb_review_*.json).
Применяются только подтверждённые правки; каждая замена проверяется (старая строка ровно 1 раз). Правит beta.html."""
import json, os
SITE = os.environ.get('SITE', '/home/user/kitayskiy-5/beta.html')
s = open(SITE, encoding='utf-8').read()
LS = s.index('const THEORY13 = [') + len('const THEORY13 = '); LE = s.index('];', LS) + 1
lit = json.loads(s[LS:LE].replace('<\\/', '</'))
DS = s.index('const D13 = ') + len('const D13 = '); DE = s.index(";\n['words', 'chars', 'sents', 'sgu', 'gram', 'phon'].forEach", DS)
D13 = json.loads(s[DS:DE].replace('<\\/', '</'))
arts = {a['id']: a for a in lit + D13['theory']}

def rep(aid, field, old, new, idx=None):
    a = arts[aid]
    if idx is None:
        assert a[field].count(old) == 1, (aid, field, old); a[field] = a[field].replace(old, new)
    else:
        assert a[field][idx].count(old) == 1, (aid, field, idx, old); a[field][idx] = a[field][idx].replace(old, new)

rep('men', 'r', 'перед существительным уже есть числительное', 'перед личным местоимением или существительным есть числительное', 1)       # учебник с. 4
rep('strokeorder', 'r', '(王, 大, 十)', '(в книге два подпункта: «сверху вниз» — 王, 打; «слева направо» — 大, 不, 林)', 0)                                           # учебник с. 46, 52
rep('strokes', 'r', '亅 shùgōu (вертикальная с крюком)', '亅 shùgōu (вертикальная с крюком влево)', 1)                                                               # учебник с. 33, 36
rep('fenbeikuai', 'n', 'Пиньинь для 一杯咖啡, 一块手表 и 4份 подписан составителем по словарикам.', 'Пиньинь для 一块手表 дан в книге (с. 95: yí kuài shǒubiǎo); для 一杯咖啡 и 4份 подписан составителем по словарикам.')
rep('zhuzai', 'r', 'В словарике урока 13: 住 — «жить, проживать», 在 — «быть, находиться в; в, на», 号 — «номер»', 'В словарике: 住 — «жить, проживать» (урок 13), 在 — «быть, находиться в; в, на» (урок 9), 号 — «номер» (урок 13)', 1)
rep('xihuan', 'n', '踢足球 («играть в футбол») дано в сноске: 踢 tī — «пинать» (с. 114).', '踢足球 tī zúqiú — «играть в футбол» (словосочетание), 踢 tī — «пинать»: блок «Дополнительная лексика», с. 115 (№ 41, 43; также словарь урока 15, с. 124).')
rep('xihuan', 'src', 'с. 114', 'с. 115')
rep('keshi', 'n', '(с. 114–115)', '(с. 115, «Дополнительная лексика»; также словарь урока 15, с. 124)')
if 'с. 114' in arts['keshi']['src']: rep('keshi', 'src', 'с. 114', 'с. 115')
# yesnochoice: в примере из учебника (с. 80–81) записано shì bu shì; СГУ (с. 79) пишет shì bú shì — пример возвращён к записи учебника, абзац поясняет оба написания
a = arts['yesnochoice']
n = 0
for e in a['ex']:
    if 'shì bú shì' in e[1]: e[1] = e[1].replace('shì bú shì', 'shì bu shì'); n += 1
assert n == 1
rep('yesnochoice', 'r', 'В СГУ (с. 79, зад. 7) эта форма записана как 是不是 (shì bú shì). В данных сайта у предложений из учебника встречается и shì bu shì (лёгкий тон в середине вопроса).',
    'В учебнике (с. 80–81) эта форма записана как shì bu shì (лёгкий тон в середине вопроса), в СГУ (с. 79, зад. 7) — как 是不是 (shì bú shì).', [k for k, p_ in enumerate(a['r']) if p_.startswith('В СГУ (с. 79, зад. 7)')][0])

def dump(o): return json.dumps(o, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
for a_, b_, t in sorted([(LS, LE, dump(lit)), (DS, DE, dump(D13))], key=lambda b: -b[0]):
    s = s[:a_] + t + s[b_:]
# вопросы грамматики уроков 1–10 лежат в основном литерале D: правим пояснения точной заменой строки
def sub(old, new):
    global s
    assert s.count(old) == 1, old; s = s.replace(old, new)
sub('"exp":"吃了吗？ (chī le ma?) — повседневное приветствие, буквально «Поел(а)?», аналог «Как дела?»"',
    '"exp":"吃了吗？ (chī le ma?) — приветствие, буквально «Поел(а)?»: его говорят в часы, близкие к приёму пищи; сегодня оно становится менее распространённым (учебник, с. 7)."')
sub('"exp":"SVO: 她(подл.) 是(глагол) 我的朋友(дополнение с определением)."',
    '"exp":"Связка 是 стоит сразу после подлежащего, а «我的朋友» — именная часть составного именного сказуемого, определение «мой» стоит перед существительным (учебник, с. 30): 她 + 是 + 我的朋友."')
open(SITE, 'w', encoding='utf-8').write(s)
print('ok')
